"""
Конфигурация бота.
Все секреты берутся из переменных окружения — не хранить токены в коде.

При запуске нужно задать:
  BOT_TOKEN          - токен Telegram-бота (получить у @BotFather)
  RECRUITER_CHAT_ID  - Telegram chat_id, куда бот присылает готовые отчёты
                        (свой личный chat_id можно узнать через @userinfobot)
  WEBHOOK_HOST        - адрес приложения, куда Telegram будет присылать
                        обновления, например https://твой-домен.twc1.net
                        (без слэша в конце). Технический домен приложения
                        виден в панели Timeweb Cloud на вкладке "Дашборд".

Необязательно:
  PROXY_URL           - адрес прокси-сервера для обращений к Telegram,
                        например socks5://логин:пароль@айпи:порт или
                        http://логин:пароль@айпи:порт. Если не задано —
                        бот обращается к Telegram напрямую.

Примечание: сейчас бот считает только "сколько правильных из скольки" —
это делает сам код, без нейросети и без затрат. Ключ Anthropic API
понадобится позже, когда решишь добавить AI-интерпретацию результатов
(в проекте уже есть готовый файл claude_analysis.py для этого).
"""
import os

BOT_TOKEN = os.environ["BOT_TOKEN"]
RECRUITER_CHAT_ID = int(os.environ["RECRUITER_CHAT_ID"])
WEBHOOK_HOST = os.environ["WEBHOOK_HOST"].rstrip("/")
PROXY_URL = os.environ.get("PROXY_URL") or None

# Лимит времени по умолчанию на один вопрос логического блока (в секундах)
DEFAULT_QUESTION_TIME_LIMIT = 60

# Время на чтение текста в блоке "Воспроизведение" (в секундах)
READING_TIME_LIMIT = 45

# Лимит времени на каждый блок теста отдельно (в секундах).
# Если кандидат не успел закончить блок за это время — блок
# принудительно завершается, и кандидату предлагают либо
# перейти к следующему блоку (с паузой на отдых), либо тест завершается.
REPRODUCTION_BLOCK_TIME_LIMIT = 5 * 60  # 5 минут на блок "Воспроизведение" (10 вопросов)
LOGIC_BLOCK_TIME_LIMIT = 16 * 60  # 16 минут на блок "Интеллект и логика"
